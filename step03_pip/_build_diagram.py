import json
import os
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
DB = r"E:\v7work\model\v7_law.sqlite"

con = sqlite3.connect("file:%s?mode=ro" % DB.replace("\\", "/"), uri=True)
bbr = json.loads(con.execute("select value from meta where key='band_by_region'").fetchone()[0])


def info(name):
    tt, col, y = con.execute(
        "select tile_type,col,y from law_tiles where tile_name=?", (name,)
    ).fetchone()
    band = bbr[min(y // 50, len(bbr) - 1)]
    sf = con.execute(
        "select start_frame from far_bands where band=? and col=?", (band, col)
    ).fetchone()[0]
    return dict(tt=tt, col=col, y=y, band=band, base=int(sf))


def word_of(y, parity):
    w = 2 * (y % 50) + parity
    return w + 1 if w >= 50 else w


def addr_table(tile_type, family, src, inf):
    rows = con.execute(
        "select frame_off,bit,parity from law_cells "
        "where tile_type=? and family=? and src_wire=?",
        (tile_type, family, src),
    ).fetchall()
    cells = sorted((fo, par, b) for fo, b, par in rows)
    return "".join(
        f"<tr><td>({fo}, {par}, {b})</td><td>{inf['base'] + fo}</td>"
        f"<td>{word_of(inf['y'], par)}</td><td>{b}</td></tr>"
        for fo, par, b in cells
    )


i8 = info("INT_L_X8Y20")
i37 = info("INT_R_X37Y199")
T1 = addr_table("INT_L", "IMUX_L40", "EE2END0", i8)
T2 = addr_table("INT_R", "SS2BEG0", "SS6END0", i37)
